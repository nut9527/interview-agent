// 本地 Mock AI 配合真实 HTTP、React 和一次性 MySQL，只使用合成面试数据。
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { liveStack } from './live-stack.mjs';
import { generateTypes } from './api-contract.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const stack = await liveStack(false);
const checks = [], errors = [];
let browser;
const output = name => new URL('../docs/evidence/' + name, import.meta.url).pathname.replace(/^\/(?=[A-Z]:)/, '');
try {
  const api = async (path, body, token, method = body ? 'POST' : 'GET', expected = 200) => {
    const response = await fetch(stack.origin + '/api' + path, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: 'Bearer ' + token } : {}) }, body: body ? JSON.stringify(body) : undefined, signal: AbortSignal.timeout(30000) });
    const result = await response.json(); assert.equal(response.status, expected, JSON.stringify(result)); return result.data;
  };
  const password = 'Acceptance123!', username = 'interview_' + Date.now();
  const owner = await api('/auth/register', { username, password, displayName: '面试流程验收' });
  const other = await api('/auth/register', { username: 'other_' + Date.now(), password, displayName: '隔离账号' });
  const token = owner.token;
  const base = '/interviews';
  let session = await startInterview(stack.origin, token, { targetRole: '数据库训练', trainingTopic: 'DATABASE', totalRounds: 3, experienceMode: 'FORMAL', timeLimitMinutes: 20 });
  assert.equal(session.experience.format, 'FORMAL'); assert.ok(!session.agent);
  const startedAt = session.experience.startedAt;
  await api(`${base}/sessions/${session.sessionId}/resources`, null, token, 'GET', 400);
  const answer = (s, n, who = token) => answerInterview(stack.origin, who, s.sessionId, { answer: '我负责验证数据库事务与隔离级别', requestId: s.sessionId + '-answer-' + n, expectedTurn: n });
  session = await answer(session, 1);
  assert.ok(!session.agent); assert.ok(!session.turns.some(t => t.content.startsWith('即时反馈：')));
  assert.equal((await api(`${base}/sessions/${session.sessionId}`, null, token)).experience.startedAt, startedAt);
  const replay = await answer(session, 1); assert.ok(!replay.agent); assert.equal(replay.turnCount, 2);
  await api(`${base}/sessions/${session.sessionId}`, null, other.token, 'GET', 404);
  const activeId = session.sessionId;
  checks.push('formal responses and idempotent replay hide evaluations and feedback; timer survives reload; ownership enforced');
  browser = await chromium.launchPersistentContext(stack.dir + '/browser', { channel: 'msedge', headless: true, reducedMotion: 'reduce', env: { ...process.env, TMP: stack.tmp, TEMP: stack.tmp }, viewport: { width: 1360, height: 1000 } });
  const page = await browser.newPage(); page.setDefaultTimeout(15000); page.on('pageerror', e => errors.push(e.message));
  await page.goto(stack.origin + '/login'); await page.getByLabel('用户名', { exact: true }).fill(username); await page.getByLabel('密码', { exact: true }).fill(password); await page.getByRole('button', { name: '登录', exact: true }).click(); await page.waitForURL('**/interview');
  await page.getByLabel('面试反馈模式').getByText('正式模拟', { exact: true }).click();
  await page.goto(stack.origin + '/interview?sessionId=' + activeId);
  await page.getByText('正式模拟 · 结束后统一复盘', { exact: true }).waitFor();
  assert.equal(await page.getByText('回答提示', { exact: true }).count(), 0);
  assert.equal(await page.getByLabel('面试 Agent 考察计划').count(), 0);
  assert.equal(await page.getByText(/即时反馈：/).count(), 0);
  await page.getByRole('timer').waitFor();
  await page.screenshot({ path: output('interview-formal.png'), fullPage: true });
  session = await answer(session, 2); session = await answer(session, 3);
  assert.equal(session.state, 'FINISHED'); assert.equal(session.agent.evaluations.length, 3);
  assert.equal(session.turns.filter(t => t.content.startsWith('即时反馈：')).length, 3);
  assert.equal(session.experience.startedAt, startedAt);
  const finalReplay = await answer(session, 1); assert.equal(finalReplay.sessionId, session.sessionId); assert.equal(finalReplay.turns.length, session.turns.length);
  let resources = await api(`${base}/sessions/${session.sessionId}/resources`, null, token);
  assert.ok(resources.length); assert.equal(resources[0].passages.length, 0); assert.ok(resources[0].exercises.length);
  const point = resources[0];
  const doc = await api('/knowledge/documents', { title: '数据库学习笔记', content: `# ${point.competency}\n\n${point.competency}的实践：通过数据库事务与隔离级别验证并发更新，记录异常与重试策略。` }, token);
  await api('/knowledge/documents', { title: '不相关笔记', content: '蛋糕配方：鸡蛋、面粉与奶油。' }, token);
  await api('/knowledge/documents', { title: '其他账号私密资料', content: point.gap + ' private-marker' }, other.token);
  resources = await api(`${base}/sessions/${session.sessionId}/resources`, null, token);
  assert.ok(resources[0].passages.some(p => p.documentId === doc.id));
  assert.ok(resources.every(r => r.passages.every(p => !p.content.includes('private-marker') && p.title !== '不相关笔记')));
  const passage = resources[0].passages.find(p => p.documentId === doc.id); assert.equal(passage.version, 1); assert.ok(passage.startLine > 0);
  checks.push('finished formal interview reveals complete review; gap recommendations return owned passages with versions/line numbers and matching exercises; empty matches stay explicit');
  const task = await api(base + '/training-tasks', { sourceSessionId: session.sessionId, sourceRound: point.round }, token);
  const duplicate = await api(base + '/training-tasks', { sourceSessionId: session.sessionId, sourceRound: point.round }, token); assert.equal(duplicate.id, task.id);
  await api(`${base}/training-tasks/${task.id}/start-commands`, { requestId: crypto.randomUUID() }, other.token, 'POST', 404);
  await api(`${base}/training-tasks/${task.id}/status`, { action: 'PAUSE' }, token);
  await api(`${base}/training-tasks/${task.id}/start-commands`, { requestId: crypto.randomUUID() }, token, 'POST', 400);
  await api(`${base}/training-tasks/${task.id}/status`, { action: 'RESUME' }, token);
  let practice = await startTrainingTask(stack.origin, token, task.id);
  practice = await answer(practice, 1); assert.ok(practice.agent); assert.ok(practice.turns.some(t => t.content.startsWith('即时反馈：')));
  let tasks = await api(base + '/training-tasks', null, token); assert.equal(tasks.items[0].answeredCount, 1); assert.equal(tasks.items[0].status, 'ACTIVE');
  await api(`${base}/training-tasks/${task.id}/status`, { action: 'PAUSE' }, token);
  await api(`${base}/training-tasks/${task.id}/status`, { action: 'RESUME' }, token);
  const secondDevice = await api('/auth/login', { username, password });
  assert.equal((await startTrainingTask(stack.origin, secondDevice.token, task.id)).sessionId, practice.sessionId);
  practice = await answer(practice, 2); practice = await answer(practice, 3);
  tasks = await api(base + '/training-tasks', null, secondDevice.token); assert.equal(tasks.items[0].status, 'COMPLETED'); assert.equal(tasks.items[0].answeredCount, 3);
  checks.push('tasks deduplicate, pause/resume, restore the same server session on a new login, show actual progress and derive completion only from finished answers');
  const exercise = resources[0].exercises[0];
  const questionTask = await api(base + '/training-tasks', { sourceSessionId: session.sessionId, sourceRound: point.round, questionId: exercise.id }, token);
  const questionSession = await startTrainingTask(stack.origin, token, questionTask.id); assert.equal(questionSession.agent.training.question.id, exercise.id);
  await page.goto(stack.origin + '/questions/' + exercise.id);
  await page.getByRole('button', { name: '练习这道题', exact: true }).click();
  await page.getByRole('combobox', { name: '选题反馈模式', exact: true }).press('ArrowDown'); await page.getByTitle('正式模拟', { exact: true }).click();
  await page.getByRole('combobox', { name: '选题计时', exact: true }).press('ArrowDown'); await page.getByTitle('10 分钟', { exact: true }).click();
  const created = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/interviews/start-commands');
  await page.getByRole('button', { name: '进入训练室', exact: true }).click();
  const formalQuestion = await awaitInterviewRun(stack.origin, token, (await (await created).json()).data);
  assert.equal(formalQuestion.experience.format, 'FORMAL'); assert.equal(formalQuestion.experience.timeLimitMinutes, 10);
  await answer(formalQuestion, 1);
  const history = await api('/questions/' + exercise.id + '/practices', null, token);
  const formalHistory = history.items.find(p => p.sessionId === formalQuestion.sessionId);
  assert.ok(formalHistory); assert.ok(formalHistory.rounds.every(r => !r.feedback && !r.level && !r.gap));
  assert.equal(formalHistory.question.referenceAnswer, ''); assert.deepEqual(formalHistory.question.followUps, []);
  checks.push('recommended question tasks start the real question; question history cannot reveal active formal feedback');
  await page.goto(stack.origin + '/interview?sessionId=' + session.sessionId);
  await page.getByLabel('薄弱点关联资料').getByText('数据库学习笔记 · v1', { exact: true }).waitFor();
  await page.getByLabel('薄弱点关联资料').screenshot({ path: output('interview-learning-desktop.png') });
  await page.getByRole('link', { name: '数据库学习笔记 · v1', exact: true }).click(); await page.getByRole('heading', { name: '数据库学习笔记', exact: true }).waitFor();
  await page.goto(stack.origin + '/interview?sessionId=' + session.sessionId);
  await page.getByRole('link', { name: '个人训练计划', exact: true }).click(); await page.getByLabel('个人训练计划').getByText('已完成', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel('个人训练计划').screenshot({ path: output('interview-plan-mobile.png') });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  const plan = page.getByLabel('个人训练计划');
  await plan.getByRole('button', { name: '暂停任务', exact: true }).click();
  await plan.getByRole('button', { name: '继续任务', exact: true }).click();
  await plan.getByRole('button', { name: '继续练习', exact: true }).click();
  await page.waitForURL('**/interview?sessionId=' + questionSession.sessionId);
  await page.goto(stack.origin + '/interview?sessionId=' + session.sessionId); await page.getByLabel('薄弱点关联资料').waitFor();
  await page.getByLabel('薄弱点关联资料').screenshot({ path: output('interview-learning-mobile.png') });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  await api('/knowledge/documents/' + doc.id, null, token, 'DELETE');
  assert.ok((await api(`${base}/sessions/${session.sessionId}/resources`, null, token)).every(r => r.passages.length === 0));
  await api(`${base}/sessions/${questionSession.sessionId}`, null, token, 'DELETE');
  tasks = await api(base + '/training-tasks', null, token); const reset = tasks.items.find(t => t.id === questionTask.id); assert.equal(reset.answeredCount, 0); assert.equal(reset.status, 'TODO');
  await api(`${base}/sessions/${session.sessionId}`, null, token, 'DELETE');
  assert.equal((await api(base + '/training-tasks', null, token)).total, 0);
  assert.deepEqual(errors, []);
  checks.push('desktop/mobile render without overflow, source links open versioned passages, deleted notes stop appearing, deleted practice resets progress, deleted source cleans its tasks');
  const contract = await (await fetch('http://127.0.0.1:18080/v3/api-docs')).json();
  assert.ok(contract.openapi);
  await writeFile(new URL('../contracts/openapi.json', import.meta.url), JSON.stringify(contract, null, 2) + '\n');
  await writeFile(new URL('../frontend/src/types/generated/openapi.ts', import.meta.url), generateTypes(contract));
  await writeFile(output('interview-learning-verification.json'), JSON.stringify({ provider: 'local-mock', checks, browserErrors: errors }, null, 2) + '\n');
  console.log(JSON.stringify({ passed: checks.length, checks }, null, 2));
} catch (e) {
  // 本地环境仅含合成夹具，命令输出保留有界诊断。
  const log = await readFile(stack.dir + '/backend.log', 'utf8').catch(() => '');
  const failure = log.lastIndexOf('ERROR');
  if (failure >= 0) console.error(log.slice(failure, failure + 7000));
  throw e;
} finally { await browser?.close(); await stack.cleanup(); }
